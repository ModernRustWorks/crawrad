def licence_files(package_dir: Path) -> list[Path]:
    """The licence files a package ships: at its root, and next to its fonts."""
    found = []
    if package_dir.is_dir():
        found += [
            p
            for p in package_dir.iterdir()
            if p.is_file() and p.name.lower().startswith(LICENSE_PREFIXES)
        ]
    fonts = package_dir / "fonts"
    if fonts.is_dir():
        found += [p for p in fonts.iterdir() if p.suffix.lower() == ".txt"]
    return sorted(found)


def standard_text(expression: str, authors: list[str]) -> tuple[str, str] | None:
    """For a package that ships no licence file: the licence we take it under
    (MIT, then Apache-2.0, then BSL-1.0, whichever its expression offers) and the
    text to print. MIT carries the package's own authors as the copyright line."""
    offered = expression.replace("/", " OR ").replace("(", " ").replace(")", " ").split()
    for spdx in ("MIT", "Apache-2.0", "BSL-1.0"):
        if spdx in offered:
            break
    else:
        return None
    if spdx == "MIT":
        body = (ROOT / "LICENSE-MIT").read_text(encoding="utf-8").split("\n", 3)[3]
        owner = ", ".join(a.split(" <")[0] for a in authors) or "the package authors"
        return spdx, f"MIT License\n\nCopyright (c) {owner}\n{body}"
    if spdx == "Apache-2.0":
        return spdx, "Full text in the section Apache License 2.0 at the end."
    return spdx, "Full text in the section Boost Software License 1.0 at the end."


def external_packages(meta: dict) -> list[dict]:
    """Every package in the resolved graph that is not a workspace member."""
    members = set(meta["workspace_members"])
    by_id = {p["id"]: p for p in meta["packages"]}
    resolved = {n["id"] for n in meta["resolve"]["nodes"]}
    out = [by_id[i] for i in resolved if i not in members and i in by_id]
    return sorted(out, key=lambda p: (p["name"], p["version"]))


def render(meta: dict) -> str:
    lines = [
        "# Third-party notices",
        "",
        "CrawRAD is built from the open source work listed below. Each package keeps",
        "its own licence; its notice and licence text follow. Source code for every",
        "package is available at crates.io under the same name and version. The",
        "MPL-2.0 packages (`resvg`, `usvg`) are used unmodified; their source is at",
        "<https://github.com/linebender/resvg>.",
        "",
        "## Fonts",
        "",
        "| Font | Copyright | Licence |",
        "|---|---|---|",
    ]
    lines += [f"| {name} | {copy} | {lic} |" for name, copy, lic in FONTS]
    lines += [
        "",
        "OFL-1.1: <https://openfontlicense.org>. CC-BY-4.0:",
        "<https://creativecommons.org/licenses/by/4.0/>. The full texts of the IDE's",
        "own fonts ship next to them under `resources/assets/fontes/`.",
        "",
        "## Rust packages",
        "",
    ]
    for pkg in external_packages(meta):
        lic = pkg.get("license") or f"see {pkg.get('license_file')}"
        repo = pkg.get("repository") or ""
        lines += [f"### {pkg['name']} {pkg['version']}", "", f"Licence: `{lic}`  ", f"Source: {repo}", ""]
        files = licence_files(Path(pkg["manifest_path"]).parent)
        for f in files:
            text = f.read_text(encoding="utf-8", errors="replace").strip()
            lines += [f"<details><summary>{f.name}</summary>", "", "```text", text, "```", "", "</details>", ""]
        if not files:
            std = standard_text(lic, pkg.get("authors") or [])
            if std is None:
                raise SystemExit(f"no licence text for {pkg['name']} {pkg['version']} ({lic})")
            lines += [f"Taken under `{std[0]}`.", "", "```text", std[1].strip(), "```", ""]
    lines += [
        "## Apache License 2.0",
        "",
        "```text",
        (ROOT / "LICENSE-APACHE").read_text(encoding="utf-8").strip(),
        "```",
        "",
        "## Boost Software License 1.0",
        "",
        "```text",
        BOOST,
        "```",
        "",
        "## SIL Open Font License 1.1",
        "",
        "The OFL-1.1 fonts in the table above are distributed under this licence",
        "(the text below is the copy that ships with JetBrains Mono).",
        "",
        "```text",
        (ROOT / "crates/crawrad-ide/assets/fontes/OFL-jetbrainsmono.txt")
        .read_text(encoding="utf-8")
        .strip(),
        "```",
    ]
    return "\n".join(lines) + "\n"


def main() -> None:
    meta = json.loads(Path(sys.argv[1]).read_text(encoding="utf-8"))
    Path(sys.argv[2]).write_text(render(meta), encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()

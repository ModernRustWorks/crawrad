//! Generated app locales module and matching logic.

/// The environment variable the generated app reads for its start language; the IDE's
/// `Run in a language` sets it.
pub const LANG_ENV: &str = "CRAWRAD_LANG";

/// Selects the best matching language code from `shipped` for a `wanted` code.
///
/// English ("en") is the fallback when no suitable shipped translation exists.
pub fn best_match(wanted: &str, shipped: &[&str]) -> String {
    let wanted_norm = wanted.replace('_', "-");
    let wanted_trimmed = wanted_norm.trim();
    if wanted_trimmed.is_empty() {
        return "en".to_string();
    }
    for &s in shipped {
        if s.replace('_', "-").eq_ignore_ascii_case(wanted_trimmed) {
            return s.to_string();
        }
    }
    let wanted_lang = wanted_trimmed.split('-').next().unwrap_or("");
    if wanted_lang.is_empty() || wanted_lang.eq_ignore_ascii_case("en") {
        return "en".to_string();
    }
    for &s in shipped {
        let s_norm = s.replace('_', "-");
        if s_norm.eq_ignore_ascii_case(wanted_lang) {
            return s.to_string();
        }
    }
    for &s in shipped {
        let s_norm = s.replace('_', "-");
        let s_lang = s_norm.split('-').next().unwrap_or("");
        if s_lang.eq_ignore_ascii_case(wanted_lang) {
            return s.to_string();
        }
    }
    "en".to_string()
}

/// A locale file as the project reads it: its code and its `(key, text, from)` entries.
pub type LocaleFile = (String, Vec<(String, String, String)>);

/// Returns the Rust source text of `src/locales.rs` for the generated app.
pub fn locales_module(files: &[LocaleFile]) -> String {
    let mut langs: Vec<&str> = files.iter().map(|(code, _)| code.as_str()).collect();
    langs.sort();
    langs.dedup();

    let mut match_arms = Vec::new();
    for (lang, entries) in files {
        for (key, text, _from) in entries {
            if text.is_empty() {
                continue;
            }
            match_arms.push((lang.as_str(), key.as_str(), text.as_str()));
        }
    }
    match_arms.sort();

    let mut text_body = String::new();
    for (lang, key, text) in match_arms {
        text_body.push_str(&format!("        ({lang:?}, {key:?}) => Some({text:?}),\n"));
    }

    let langs_formatted: Vec<String> = langs.iter().map(|l| format!("{l:?}")).collect();
    let langs_slice = langs_formatted.join(", ");

    format!(
        r#"// Generated by CrawRAD from locales/*.toml — do not edit.

/// The languages this app ships besides English.
pub const LANGUAGES: &[&str] = &[{langs_slice}];

/// The translation of `key` in `lang`, if there is one.
pub fn text(lang: &str, key: &str) -> Option<&'static str> {{
    match (lang, key) {{
{text_body}        _ => None,
    }}
}}

/// The language to start in: `CRAWRAD_LANG`, else the system's, matched to a shipped one, else "en".
pub fn language() -> String {{
    if let Ok(lang) = std::env::var("CRAWRAD_LANG") {{
        let trimmed = lang.trim();
        if !trimmed.is_empty() {{
            return best_match(trimmed);
        }}
    }}
    if let Some(locale) = sys_locale::get_locale() {{
        return best_match(&locale);
    }}
    "en".to_string()
}}

/// `pt-PT` → `pt-BR` when only `pt-BR` ships; an exact code wins; unknown → "en".
pub fn best_match(wanted: &str) -> String {{
    let wanted_norm = wanted.replace('_', "-");
    let wanted_trimmed = wanted_norm.trim();
    if wanted_trimmed.is_empty() {{
        return "en".to_string();
    }}
    for &s in LANGUAGES {{
        if s.replace('_', "-").eq_ignore_ascii_case(wanted_trimmed) {{
            return s.to_string();
        }}
    }}
    let wanted_lang = wanted_trimmed.split('-').next().unwrap_or("");
    if wanted_lang.is_empty() || wanted_lang.eq_ignore_ascii_case("en") {{
        return "en".to_string();
    }}
    for &s in LANGUAGES {{
        let s_norm = s.replace('_', "-");
        if s_norm.eq_ignore_ascii_case(wanted_lang) {{
            return s.to_string();
        }}
    }}
    for &s in LANGUAGES {{
        let s_norm = s.replace('_', "-");
        let s_lang = s_norm.split('-').next().unwrap_or("");
        if s_lang.eq_ignore_ascii_case(wanted_lang) {{
            return s.to_string();
        }}
    }}
    "en".to_string()
}}
"#
    )
}


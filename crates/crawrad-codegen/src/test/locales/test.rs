use super::*;

#[test]
fn best_match_table_cases() {
    let shipped = &["de", "pt-BR"];

    assert_eq!(best_match("pt-BR", shipped), "pt-BR");
    assert_eq!(best_match("pt_BR", shipped), "pt-BR");
    assert_eq!(best_match("pt-PT", shipped), "pt-BR");
    assert_eq!(best_match("de-AT", shipped), "de");
    assert_eq!(best_match("fr", shipped), "en");
    assert_eq!(best_match("en-US", shipped), "en");
    assert_eq!(best_match("", shipped), "en");

    // Case-insensitivity check
    assert_eq!(best_match("PT-br", shipped), "pt-BR");
    assert_eq!(best_match("DE", shipped), "de");
}

#[test]
fn locales_module_emits_expected_content() {
    let files = vec![
        (
            "de".to_string(),
            vec![
                (
                    "form_main.btn_ok.text".to_string(),
                    "OK".to_string(),
                    "OK".to_string(),
                ),
                (
                    "form_main.lbl.text".to_string(),
                    "Hallo \"Welt\"\\".to_string(),
                    "Hello".to_string(),
                ),
                // Empty text should be skipped
                (
                    "form_main.empty.text".to_string(),
                    "".to_string(),
                    "Source".to_string(),
                ),
            ],
        ),
        (
            "pt-BR".to_string(),
            vec![(
                "form_main.btn_ok.text".to_string(),
                "Confirmar".to_string(),
                "OK".to_string(),
            )],
        ),
    ];

    let output = locales_module(&files);

    assert!(output.contains("// Generated by CrawRAD from locales/*.toml — do not edit."));
    assert!(output.contains(r#"pub const LANGUAGES: &[&str] = &["de", "pt-BR"];"#));
    assert!(output.contains(r#"("de", "form_main.btn_ok.text") => Some("OK"),"#));
    assert!(output.contains(r#"("de", "form_main.lbl.text") => Some("Hallo \"Welt\"\\"),"#));
    assert!(output.contains(r#"("pt-BR", "form_main.btn_ok.text") => Some("Confirmar"),"#));
    assert!(!output.contains("form_main.empty.text"));
    assert!(output.contains("pub fn language() -> String"));
    assert!(output.contains("pub fn best_match(wanted: &str) -> String"));
}

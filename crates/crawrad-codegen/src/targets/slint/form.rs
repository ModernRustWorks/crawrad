//! Slint `<form>.designer.rs` and `<form>.slint` code generation.

use super::components;
use super::layout::{is_inside_container, text};
use crate::{Erro, identificador};
use crawrad_ir::{Document, Node};

/// Generates the standalone `.slint` markup for the form.
pub fn form_slint(
    // Source document being compiled
    doc: &Document,
    // Component registry
    reg: &crawrad_registry::Registry,
    // Root form node
    root: &Node,
    // Canonical name of the form
    form_type: &str,
    // Emitted component nodes
    emitted: &[&Node],
) -> Result<String, Erro> {
    let title = text(root);
    let title_esc = super::components::util::escape_slint_string(&title);
    let rect = root
        .rect()
        .unwrap_or(crawrad_ir::Rect::new(0.0, 0.0, 800.0, 600.0));
    let width = rect.w;
    let height = rect.h;

    let mut callbacks = Vec::new();
    let mut properties = Vec::new();
    let mut children_slint = String::new();

    for node in emitted {
        callbacks.extend(components::slint_callbacks(node));
        properties.extend(components::slint_properties(node));

        if is_inside_container(doc, reg, &node.id) {
            continue;
        }

        let node_rect = doc
            .rect_in_form(&node.id)
            .unwrap_or(crawrad_ir::Rect::new(0.0, 0.0, 80.0, 24.0));

        let elem = components::emit_slint(
            doc,
            reg,
            node,
            node_rect.x,
            node_rect.y,
            node_rect.w,
            node_rect.h,
        )?;
        children_slint.push_str(&elem);
    }

    let mut std_widgets_needed = std::collections::BTreeSet::new();
    for node in emitted {
        let effective = reg.effective_class(&node.class);
        for &w in components::std_widgets(effective) {
            std_widgets_needed.insert(w);
        }
    }

    let mut out = String::new();
    out.push_str("// Generated by CrawRAD - Slint UI markup\n\n");
    if !std_widgets_needed.is_empty() {
        let widgets_list = std_widgets_needed
            .into_iter()
            .collect::<Vec<_>>()
            .join(", ");
        out.push_str(&format!(
            "import {{ {widgets_list} }} from \"std-widgets.slint\";\n\n"
        ));
    }
    out.push_str(&format!(
        "export component {form_type}Window inherits Window {{\n"
    ));
    out.push_str(&format!("    title: \"{title_esc}\";\n"));
    out.push_str(&format!("    width: {width:.1}px;\n"));
    out.push_str(&format!("    height: {height:.1}px;\n\n"));

    for cb in callbacks {
        out.push_str(&format!("    {cb}\n"));
    }
    for prop in properties {
        out.push_str(&format!("    {prop}\n"));
    }
    if !children_slint.is_empty() {
        out.push('\n');
        out.push_str(&children_slint);
    }
    out.push_str("}\n");

    Ok(out)
}

/// Generates `<form>.designer.rs` for Slint projects.
pub fn form_designer_rs(
    // Source document
    doc: &Document,
    // Component registry
    reg: &crawrad_registry::Registry,
    // Root form node
    root: &Node,
    // Canonical name of the form
    form_type: &str,
    // Emitted component nodes
    emitted: &[&Node],
) -> Result<String, Erro> {
    form_designer_rs_with_base(doc, reg, root, form_type, emitted, &[], false)
}

pub(crate) fn form_designer_rs_with_base(
    // Source document
    doc: &Document,
    // Component registry
    reg: &crawrad_registry::Registry,
    // Root form node
    root: &Node,
    // Canonical name of the form
    form_type: &str,
    // Emitted component nodes
    emitted: &[&Node],
    // Optional base documents for inheritance
    _bases: &[Document],
    // Flag indicating if this form is a base
    _is_base: bool,
) -> Result<String, Erro> {
    let _form_name = identificador(root.name())?;
    let slint_markup = form_slint(doc, reg, root, form_type, emitted)?;

    let mut fields = String::new();
    let mut default_fields = String::new();
    let mut actions = String::new();
    let mut sync_lines = String::new();

    for n in emitted {
        let field = identificador(n.name())?;
        let class_name = &n.class;
        fields.push_str(&format!("    pub {field}: {class_name},\n"));

        let init = components::emit_default_com(reg, doc, n);
        default_fields.push_str(&format!("            {field}: {init},\n"));

        let action_code = components::emit_actions(doc, n, &field, emitted)?;
        actions.push_str(&action_code);

        let sync_code = components::emit_sync(doc, n, &field);
        sync_lines.push_str(&sync_code);
    }

    let initial_state_ident = match root.props.get("window_state") {
        Some(crawrad_ir::Value::Enum(s)) | Some(crawrad_ir::Value::Str(s)) => match s.as_str() {
            "wsMaximized" => "Maximized",
            "wsMinimized" => "Minimized",
            "wsFullScreen" => "FullScreen",
            _ => "Normal",
        },
        _ => "Normal",
    };

    let component_structs = components::component_structs(doc, reg);

    Ok(format!(
        "// Generated by CrawRAD - do not edit this file directly.\n\
         \n\
         use std::sync::{{Arc, Mutex}};\n\
         use crawrad_runtime::prelude::*;\n\
         use crawrad_runtime_slint::*;\n\
         \n\
         slint::slint! {{\n\
         {slint_markup}\
         }}\n\
         \n\
         {component_structs}\n\
         #[derive(Debug, Clone)]\n\
         pub struct {form_type} {{\n\
         {fields}\
         }}\n\
         \n\
         impl Default for {form_type} {{\n\
         \x20   fn default() -> Self {{\n\
         \x20       Self {{\n\
         {default_fields}\
         \x20       }}\n\
         \x20   }}\n\
         }}\n\
         \n\
         pub struct {form_type}App {{\n\
         \x20   pub form: {form_type},\n\
         }}\n\
         \n\
         pub fn app_main() {{\n\
         \x20   let initial_window_state = FormWindowState::{initial_state_ident};\n\
         \x20   if let Ok(window) = {form_type}Window::new() {{\n\
         \x20       match initial_window_state {{\n\
         \x20           FormWindowState::Maximized => window.window().set_maximized(true),\n\
         \x20           FormWindowState::Minimized => window.window().set_minimized(true),\n\
         \x20           FormWindowState::FullScreen => window.window().set_fullscreen(true),\n\
         \x20           FormWindowState::Normal => {{}},\n\
         \x20       }}\n\
         \x20       let app = Arc::new(Mutex::new({form_type}App {{\n\
         \x20           form: {form_type}::default(),\n\
         \x20       }}));\n\
         \n\
         {sync_lines}\
         {actions}\
         \n\
         \x20       let _ = window.run();\n\
         \x20   }}\n\
         }}\n"
    ))
}

//! Generating the `src/main.rs` file for applications based on `eframe` / `egui`.

use crate::{SUFIXO_GERADO, literal};
use crawrad_ir::Node;

const MAIN_RS: &str = r#"//! GENERATED BY CrawRAD. Rewritten on every generation —
//! your code goes in `@FORM@.rs`.

// No console window behind your app on Windows — but only in a release build.
// While you develop you want `panic!` and `println!` to have somewhere to go;
// the person who runs the finished program does not want a black rectangle
// behind the window.
#![cfg_attr(not(debug_assertions), windows_subsystem = "windows")]

mod @FORM@;
@LOCALES_MOD@
// The WinForms convention (`Form1.Designer.cs`): the designer code lives in
// its own file, named after whose it is. It stays a `.rs` on purpose — hiding
// it at the cost of highlighting and rust-analyzer would be expensive on the
// day something goes wrong.
// `pub`, the same as the Makepad target: the box types it carries (`Color`,
// `Font`, ...) are API for YOUR code, not only for the designer's.
#[path = "@FORM@@SUFIXO@"]
pub mod @FORM@_designer;

use @FORM@_designer::@TIPO@;

// Not `-> eframe::Result`: in release there is no console, and a returned
// error would go to a stderr nobody reads — the program would simply not
// open. The person who runs it gets a message box and a log beside the exe.
fn main() -> std::process::ExitCode {
@LANGUAGE_PICK@    let opcoes = eframe::NativeOptions {
        viewport: eframe::egui::ViewportBuilder::default()
            .with_inner_size(@TIPO@::SIZE)
            .with_title(@WINDOW_TITLE@)@VIEWPORT@,
@CENTERED@        ..Default::default()
    };
    // `new()` — and not `default()`: it is what runs your `OnCreate`, once,
    // before the first frame is drawn.
    let mut form = @TIPO@::new();
@LANGUAGE_INIT@@THEME_INIT@    match eframe::run_ui_native(@TITULO@, opcoes, move |ui, _frame| {
@THEME_APPLY@        form.show(ui);
    }) {
        Ok(()) => std::process::ExitCode::SUCCESS,
        Err(error) => {
            crawrad_runtime::report_startup_failure(@TITULO@, &error);
            std::process::ExitCode::FAILURE
        }
    }
}
"#;

pub fn main_rs(form: &str, tipo: &str, raiz: &Node) -> String {
    // the form's Theme, installed once; `thSystem` leaves it to eframe,
    // which follows the system
    let preference = match raiz.props.get("theme") {
        Some(crawrad_ir::Value::Enum(s)) if s == "thLight" => Some("Light"),
        Some(crawrad_ir::Value::Enum(s)) if s == "thDark" => Some("Dark"),
        _ => None,
    };
    let (theme_init, theme_apply) = match preference {
        Some(p) => (
            "    let mut themed = false;\n".to_string(),
            format!(
                "        if !themed {{\n            ui.ctx().set_theme(eframe::egui::ThemePreference::{p});\n            themed = true;\n        }}\n"
            ),
        ),
        None => (String::new(), String::new()),
    };

    let english_title = literal(raiz.text().unwrap_or(raiz.name()));
    // with languages, the window opens titled in the chosen one (the caption's key) and
    // the form's texts follow; the app id (`run_ui_native`) stays the English caption.
    let (locales_mod, language_pick, language_init, window_title) = if super::has_locales() {
        let key = crawrad_ir::text_key(form, &raiz.id, "text");
        (
            "mod locales;\n".to_string(),
            "    let language = crate::locales::language();\n".to_string(),
            "    form.apply_language(&language);\n".to_string(),
            format!("crate::locales::text(&language, {key:?}).unwrap_or({english_title})"),
        )
    } else {
        (
            String::new(),
            String::new(),
            String::new(),
            english_title.clone(),
        )
    };

    MAIN_RS
        .replace("@FORM@", form)
        .replace("@LOCALES_MOD@", &locales_mod)
        .replace("@LANGUAGE_PICK@", &language_pick)
        .replace("@LANGUAGE_INIT@", &language_init)
        .replace("@WINDOW_TITLE@", &window_title)
        .replace("@SUFIXO@", SUFIXO_GERADO)
        .replace("@TIPO@", tipo)
        .replace("@TITULO@", &english_title)
        .replace("@THEME_INIT@", &theme_init)
        .replace("@THEME_APPLY@", &theme_apply)
        // WindowState and Position, the viewport's and eframe's own
        .replace(
            "@VIEWPORT@",
            match raiz.props.get("window_state") {
                Some(crawrad_ir::Value::Enum(s)) if s == "wsMaximized" => "\n            .with_maximized(true)",
                Some(crawrad_ir::Value::Enum(s)) if s == "wsMinimized" => "\n            .with_minimized(true)",
                _ => "",
            },
        )
        .replace(
            "@CENTERED@",
            if matches!(raiz.props.get("position"), Some(crawrad_ir::Value::Enum(s)) if s == "poScreenCenter") {
                "        centered: true,\n"
            } else {
                ""
            },
        )
}

/// The builder call that opens the window's viewport in [`main_rs`].
/// The project's `icon.png`, decoded when the window opens; a bad file means no icon.
const ICON_EXPR: &str =
    r#"eframe::icon_data::from_png_bytes(include_bytes!("../icon.png")).unwrap_or_default()"#;

const VIEWPORT_ANCHOR: &str = "eframe::egui::ViewportBuilder::default()";

/// `main` with the window showing the project's `icon.png` in its title bar
/// (and taskbar / dock). Untouched when it is not an egui `main` or already has it.
pub fn with_window_icon(main: &str) -> String {
    if main.contains(".with_icon(") {
        return main.to_string();
    }
    main.replacen(
        VIEWPORT_ANCHOR,
        &format!("{VIEWPORT_ANCHOR}\n            .with_icon({ICON_EXPR})"),
        1,
    )
}
